// Pre-render figlet banners at build time into src/banners.js.
// No runtime font loading; the ASCII is checked in like any other asset.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import figlet from "figlet";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "banners.js");

const render = (text, font, options = {}) =>
  figlet.textSync(text, { font, horizontalLayout: "default", ...options });

const bannerHero = render("screenagents", "ANSI Shadow", {
  horizontalLayout: "fitted",
});
const bannerSmall = render("screenagents", "Small");
const bannerFooter = render("screenagents", "Mini");

const width = (art) => Math.max(...art.split("\n").map((l) => [...l].length));

const file = `// Generated by scripts/gen-banners.mjs — do not edit by hand.
// Regenerate with: npm run banners

export const BANNER_HERO = ${JSON.stringify(bannerHero)};
export const BANNER_SMALL = ${JSON.stringify(bannerSmall)};
export const BANNER_MINI = ${JSON.stringify(bannerFooter)};

export const BANNER_WIDTHS = ${JSON.stringify({
  hero: width(bannerHero),
  small: width(bannerSmall),
  mini: width(bannerFooter),
})};
`;

writeFileSync(out, file);
console.log(
  `wrote ${out}\n  hero: ${width(bannerHero)} cols\n  small: ${width(bannerSmall)} cols\n  mini: ${width(bannerFooter)} cols`
);
